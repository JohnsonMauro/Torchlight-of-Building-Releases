// The game keywords: how scripts/fetch-tlidb-keywords.js reads TLIDB's pages, what the generated
// src/data/game/keywords.generated.js holds, and how src/engine/text/game-keywords.js finds keywords in a text.
import { test } from "node:test";
import assert from "node:assert/strict";
import { buildKeywords, parseGlossary, parseHoverCard, parseMarks } from "../../scripts/fetch-tlidb-keywords.js";
import { GAME_KEYWORD_FORMS, GAME_KEYWORDS } from "../../src/data/game/keywords.generated.js";
import { gameKeyword, gameKeywordSegments, gameKeywordsExplained } from "../../src/engine/text/game-keywords.js";

const mark = (id, page, form) =>
  `<e id=${id} class="Hyperlink" data-hover="/cache/en/Torchlight_Hyperlink_hover/h${id}" href="${page}">${form}</e>`;
const row = (page, name, cell) => `<tr><td><a href="${page}">${name}</a></td><td>${cell}</td></tr>`;
const glossaryPage = (...rows) =>
  `<div class="card-header">Hyperlink /${rows.length} </div><table><tbody>${rows.join("")}`;

test("the glossary keeps each page's distinct definitions, line breaks as \\n, without empty rows", () => {
  const glossary = parseGlossary(
    glossaryPage(
      row("Spell_Burst", "Spell Burst", `Uses a Spell.<br/>When ${mark(756, "Spell_Burst", "Spell Burst")} is full`),
      row("Lock", "Lock", "Track locks on"),
      row("Lock", "Lock", "Lock On locks on"),
      row("Lock", "Lock", "Track locks on"),
      row("", "", ""),
      row("Trinity", "Trinity", ""),
    ),
  );
  assert.deepEqual(Object.fromEntries(glossary), {
    Spell_Burst: { name: "Spell Burst", definitions: ["Uses a Spell.\nWhen Spell Burst is full"] },
    Lock: { name: "Lock", definitions: ["Track locks on", "Lock On locks on"] },
  });
});

test("a glossary whose rows do not match its declared count, or with unknown markup, is refused", () => {
  assert.throws(() => parseGlossary(glossaryPage(row("Blur", "Blur", "x")).replace("/1 ", "/2 ")), /Expected 2/);
  assert.throws(() => parseGlossary(glossaryPage(row("Blur", "Blur", "<b>Blur</b>"))), /Unparsed markup/);
});

test("a hover card gives its keyword's id and text", () => {
  const card = `<h5 class="card-title" data-id="172">${mark(172, "Lock", "Lock")}</h5>
        <div class="card-text">
        Lock On locks on<br/>enemies
        </div>`;
  assert.deepEqual(parseHoverCard(card), { id: 172, text: "Lock On locks on\nenemies" });
});

test("keywords are the marked ones: forms to the id the texts use most, plain words left out, cards for duplicates", () => {
  const glossary = parseGlossary(
    glossaryPage(
      row("Frostbite", "Frostbite", "the ailment"),
      row("Frostbite", "Frostbite", "the rating"),
      row("Tangle", "Tangle", "attaches to an enemy"),
      row("Enemy_Count", "Enemy Count", "counts enemies"),
      row("Mana", "Mana", "20% of damage is taken from Mana"),
    ),
  );
  const marks = parseMarks(
    [
      mark(735, "Frostbite", "Frostbitten"),
      mark(735, "Frostbite", "Frostbite Rating"),
      mark(736, "Frostbite", "Frostbite Rating"),
      mark(736, "Frostbite", "Frostbite Rating"),
      mark(767, "Tangle", " Tangle(s) "),
      mark(9, "Enemy_Count", "each enemy"),
    ].join(" "),
  );
  const hoverTexts = new Map([
    [735, "the ailment"],
    [736, "the rating"],
  ]);
  assert.deepEqual(buildKeywords({ glossary, marks, hoverTexts }), {
    keywords: {
      735: { name: "Frostbite", page: "Frostbite", definition: "the ailment" },
      736: { name: "Frostbite", page: "Frostbite", definition: "the rating" },
      767: { name: "Tangle", page: "Tangle", definition: "attaches to an enemy" },
    },
    forms: { "Frostbite Rating": 736, Frostbitten: 735, "Tangle(s)": 767 },
  });
  assert.throws(() => buildKeywords({ glossary, marks, hoverTexts: new Map() }), /several definitions/);
});

test("the generated keywords hold the game's wording and only words the game links", () => {
  assert.equal(
    GAME_KEYWORDS[767].definition,
    "Generated by the player, it can attach to an enemy and periodically trigger a specified Spell Skill",
  );
  assert.match(GAME_KEYWORDS[756].definition, /^Automatically uses a Spell Skill/);
  for (const form of ["Spell Burst", "Tangle(s)", "Blur", "Agility Blessing", "Frostbitten"])
    assert.ok(GAME_KEYWORD_FORMS[form], form);
  for (const form of ["Mana", "Sentry", "Armor", "Recent", "each enemy", "Resistance"])
    assert.equal(GAME_KEYWORD_FORMS[form], undefined, form);
  for (const id of Object.values(GAME_KEYWORD_FORMS)) assert.ok(GAME_KEYWORDS[id], `form for missing keyword ${id}`);
  assert.ok(Object.values(GAME_KEYWORDS).every(({ definition }) => definition && !/[<>]/.test(definition)));
});

const marked = (text) =>
  gameKeywordSegments(text)
    .map((segment) => (segment.keyword ? `[${segment.text}]` : segment.text))
    .join("");

test("a text is split at the forms the game writes, longest first, never inside a longer word", () => {
  assert.equal(marked("+1 Tangle(s) Quantity for Spell Skills"), "+1 [Tangle(s)] Quantity for Spell Skills");
  assert.equal(marked("Nearby enemies are Paralyzed"), "[Nearby] enemies are [Paralyzed]");
  assert.equal(marked("+25% Max Fire Resistance"), "+25% [Max Fire Resistance]");
  assert.equal(
    marked("Recently used +12% Max Mana; Multistrike-only"),
    "Recently used +12% Max Mana; Multistrike-only",
  );
  assert.equal(marked("Frostbitten\nBlur"), "[Frostbitten]\n[Blur]");
  assert.deepEqual(gameKeywordSegments(""), [{ text: "" }]);
  const [, spellBurst] = gameKeywordSegments("Gains Spell Burst");
  assert.deepEqual(gameKeyword(spellBurst.keyword), {
    id: 756,
    name: "Spell Burst",
    definition: GAME_KEYWORDS[756].definition,
  });
  assert.equal(gameKeyword(1), null);
});

const names = (ids) => ids.map((id) => GAME_KEYWORDS[id].name);

test("a tooltip explains its keywords, then the ones their definitions name, one level deep, each once", () => {
  // Blur's definition names Blur Rating, whose own definition names only Blur (Rating) again.
  assert.deepEqual(names(gameKeywordsExplained([721])), ["Blur", "Blur Rating"]);
  // Frostbite names Ailment, Frostbite Rating and Freeze; Ailment's and Freeze's own keywords stay out.
  assert.deepEqual(names(gameKeywordsExplained([735, 735, 1])), ["Frostbite", "Ailment", "Frostbite", "Freeze"]);
  assert.deepEqual(gameKeywordsExplained([]), []);
});
